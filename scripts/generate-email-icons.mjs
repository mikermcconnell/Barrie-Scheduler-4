// Renders the daily email's duotone icons to PNG and writes them as base64 into
// functions/src/emailIconData.ts. The email embeds them as inline (cid) attachments.
// Run: node scripts/generate-email-icons.mjs
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const GLYPHS = {
  bus: '<rect x="5" y="3" width="14" height="15" rx="3"/><path d="M5 11h14"/><path d="M9.5 6h5"/><circle cx="8.5" cy="14.5" r=".9"/><circle cx="15.5" cy="14.5" r=".9"/><path d="M7.5 18v2.5M16.5 18v2.5"/>',
  performance: '<circle cx="12" cy="12" r="9"/><path d="M12 7v5l3.5 2"/>',
  ridership: '<circle cx="9" cy="8" r="3.5"/><path d="M2.5 20.5a6.5 6.5 0 0 1 13 0"/><circle cx="17.2" cy="9" r="2.6"/><path d="M16.5 14.3a5 5 0 0 1 5.5 5"/>',
  trips: '<circle cx="6" cy="19" r="2.5"/><circle cx="18" cy="5" r="2.5"/><path d="M8.5 19H16a3.5 3.5 0 0 0 0-7H8a3.5 3.5 0 0 1 0-7h7.5"/>',
  dwell: '<circle cx="12" cy="14" r="7.5"/><path d="M12 14v-3.5"/><path d="M10 2.5h4M12 2.5v4"/><path d="M18.3 7.2l1.5-1.5"/>',
};

// Every colour each icon can take in the email. Card colours follow the KPI accent.
const VARIANTS = [
  { name: 'bus', color: '#ffffff', glyphSize: 24, badgeBg: '#0f3a76', badgeBorder: '#ffffff33' },
  ...['#16a34a', '#d97706', '#dc2626'].map(color => ({ name: 'performance', color })),
  { name: 'ridership', color: '#2563eb' },
  ...['#6d28d9', '#dc2626'].map(color => ({ name: 'trips', color })),
  ...['#0891b2', '#d97706'].map(color => ({ name: 'dwell', color })),
];

function badgeHtml({ name, color, glyphSize = 18, badgeBg = '#f8fafc', badgeBorder = `${color}33` }) {
  const box = glyphSize + 14;
  return `<span id="icon" style="display:inline-flex;align-items:center;justify-content:center;box-sizing:border-box;width:${box}px;height:${box}px;border-radius:14px;background:${badgeBg};border:1px solid ${badgeBorder};">
    <svg viewBox="0 0 24 24" width="${glyphSize}" height="${glyphSize}" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
      <style>rect,circle{fill:${color};fill-opacity:.18}</style>${GLYPHS[name]}
    </svg></span>`;
}

const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 2 });
const entries = [];
for (const variant of VARIANTS) {
  await page.setContent(`<body style="margin:0;background:transparent">${badgeHtml(variant)}</body>`);
  const png = await page.locator('#icon').screenshot({ omitBackground: true });
  entries.push(`  '${variant.name}-${variant.color.slice(1)}': '${png.toString('base64')}',`);
}
await browser.close();

const out = fileURLToPath(new URL('../functions/src/emailIconData.ts', import.meta.url));
writeFileSync(out, `// Generated by scripts/generate-email-icons.mjs. Do not edit by hand.
// Key: <icon>-<hex colour>. Value: base64 PNG of the icon badge at 2x.
export const EMAIL_ICON_PNG: Record<string, string> = {
${entries.join('\n')}
};
`);
console.log(`Wrote ${entries.length} icons to ${out}`);
