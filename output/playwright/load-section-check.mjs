import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
const shot = name => page.locator('[data-testid="ridership-load-section"]').screenshot({ path: `output/playwright/load-section/${name}.png` });
await page.goto('http://127.0.0.1:5199/output/playwright/load-section-harness.html', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.getByText('Load Along the Route').waitFor({ timeout: 90000 });
await page.waitForTimeout(800);
await page.screenshot({ path: 'output/playwright/load-section/01-all-day-full.png', fullPage: true });
await page.getByRole('button', { name: /^AM peak/ }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: 'output/playwright/load-section/02-am-peak-full.png', fullPage: true });
await page.getByRole('button', { name: /^All day/ }).click();
await page.waitForTimeout(400);
await page.locator('[data-testid="ridership-busiest-trips"] tbody tr').first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: 'output/playwright/load-section/03-trip-selected-full.png', fullPage: true });
const chartBox = await page.locator('.recharts-wrapper').first().boundingBox();
await page.mouse.move(chartBox.x + chartBox.width * 0.45, chartBox.y + chartBox.height * 0.5);
await page.waitForTimeout(400);
await page.screenshot({ path: 'output/playwright/load-section/04-tooltip.png', fullPage: false });
const overflow = await page.evaluate(() => ({ doc: document.documentElement.scrollWidth, vw: innerWidth }));
console.log(JSON.stringify({ errors, overflow }));
await browser.close();
